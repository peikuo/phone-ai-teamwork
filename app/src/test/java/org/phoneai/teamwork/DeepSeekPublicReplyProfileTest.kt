package org.phoneai.teamwork

import org.junit.Assert.*
import org.junit.Test
import org.phoneai.teamwork.agent.*
import org.phoneai.teamwork.state.*
import org.phoneai.teamwork.targets.*
import org.phoneai.teamwork.workflow.*

class DeepSeekPublicReplyProfileTest {
    private val participant = Participant("deepseek", "DeepSeek", "com.deepseek.chat", "2.5.2 (273)")
    private val recipe = Recipe.discussion(DeepSeekProbeProfile.GOAL, listOf(participant), participant.id)
    private val payload = PayloadBuilder.build(recipe, recipe.steps.first())
    private val step = recipe.steps.first().copy(status = TurnStatus.SUBMITTING, payloadId = payload.id)
    private val task = recipe.copy(steps = listOf(step), status = TaskStatus.RUNNING, pendingIntent = "send-1",
        payloads = mapOf(payload.id to payload),
        bindings = mapOf("deepseek" to ThreadBinding(recipe.id, "deepseek", "", "", participant.version, initialWindowId = 7)))
    private val prefix = "0/0/0/0/0"
    private fun node(path: String, text: String = "", description: String = "", bounds: String = "0 0 10 10") =
        UiNode(path, null, text, description, false, false, bounds, className = "android.widget.TextView")
    private val user = node("$prefix/1/0/1/0/0/0", payload.text, bounds = "231 325 996 793")
    private val answer = node("$prefix/2/0/0", DeepSeekProbeProfile.ANSWER, bounds = "63 967 360 1041")
    private val copy = node("$prefix/2/0/1/0", description = "Copy", bounds = "68 1091 121 1144")
    private val regenerate = node("$prefix/2/0/6/0", description = "Regenerate", bounds = "964 1091 1017 1144")
    private val title = node("$prefix/1/0/3/0", DeepSeekProbeProfile.ANSWER, bounds = "159 144 434 200")
    private val observation = UiObservation("snapshot", task.id, participant.packageName, 7, 1, 1000,
        listOf(user, answer, copy, regenerate, title,
            node("$prefix/3/0/0/0", "Type a message or hold to speak", bounds = "77 2089 998 2156"),
            node("$prefix/9", "Generated by DeepSeek AI", bounds = "0 2331 1080 2363")),
        participant.version, false, false, false)

    @Test fun completePublicExchangeHasSeparateUserAndAssistantEvidence() {
        val result = DeepSeekPublicReplyProfile.verify(task, observation, 1100)
        assertEquals(user.path, result?.userPath)
        assertEquals(answer.path, result?.answerPath)
        assertEquals(DeepSeekProbeProfile.ANSWER, result?.answer)
    }

    @Test fun missingCompletionWrongConversationAndExtraContentFailClosed() {
        assertNull(DeepSeekPublicReplyProfile.verify(task, observation.copy(nodes = observation.nodes - regenerate), 1100))
        assertNull(DeepSeekPublicReplyProfile.verify(task, observation.copy(nodes = observation.nodes +
            node("$prefix/2/0/7/0", description = "Stop generating")), 1100))
        assertNull(DeepSeekPublicReplyProfile.verify(task, observation.copy(nodes = observation.nodes - answer), 1100))
        assertNull(DeepSeekPublicReplyProfile.verify(task, observation.copy(nodes = observation.nodes + user.copy(path = "$prefix/3")), 1100))
        assertNull(DeepSeekPublicReplyProfile.verify(task, observation.copy(nodes = observation.nodes +
            node("$prefix/4", "unexpected private message")), 1100))
        assertNull(DeepSeekPublicReplyProfile.verify(task, observation.copy(windowId = 8), 1100))
        assertNull(DeepSeekPublicReplyProfile.verify(task, observation.copy(appVersion = "changed"), 1100))
        assertNull(DeepSeekPublicReplyProfile.verify(task, observation.copy(at = 1000), 7000))
        assertNull(DeepSeekPublicReplyProfile.verify(task.copy(pendingIntent = null), observation, 1100))
        assertNull(DeepSeekPublicReplyProfile.verify(task.copy(status = TaskStatus.NEEDS_USER), observation, 1100))
    }
}
