package org.phoneai.teamwork

import org.junit.Assert.*
import org.junit.Test
import org.phoneai.teamwork.agent.*
import org.phoneai.teamwork.state.*
import org.phoneai.teamwork.targets.DeepSeekProbeProfile
import org.phoneai.teamwork.workflow.Recipe

class DeepSeekProbeProfileTest {
    private val participant = Participant("deepseek", "DeepSeek", "com.deepseek.chat", "2.5.2 (273)")
    private val recipe = Recipe.discussion(DeepSeekProbeProfile.GOAL, listOf(participant), participant.id)
    private val task = recipe.copy(steps = recipe.steps.take(1))
    private fun node(path: String, text: String = "", description: String = "") =
        UiNode(path, null, text, description, false, false, "0 0 100 100")
    private val input = node("0/3").copy(editable = true, supportedActions = setOf(2097152))
    private fun observation(greeting: String) = UiObservation("fixture", task.id, participant.packageName, 1, 1, 1000,
        listOf(node("0").copy(className = "androidx.compose.ui.platform.ComposeView"),
            node("0/1", greeting), node("0/2", description = "开启新对话"), input,
            node("0/4", "回答由 AI 生成，仅供参考").copy(visible = false)), participant.version, false, false, false)

    @Test fun observedDayAndEveningGreetingsAreAccepted() {
        for (greeting in listOf("你好，有什么我能帮你的吗？", "晚上好，有什么我能帮你的吗？", "欢迎回来，想从哪里开始？")) {
            val o = DeepSeekProbeProfile.classify(task, observation(greeting))
            assertTrue(o.profileVerified)
            assertEquals(NodeRole.INPUT, o.nodes.single { it.path == input.path }.role)
        }
        val english = observation("Hi! What's on your mind today?").copy(nodes =
            observation("Hi! What's on your mind today?").nodes.map {
                if (it.description == "开启新对话") it.copy(description = "New chat") else it
            })
        assertTrue(DeepSeekProbeProfile.classify(task, english.copy(nodes = english.nodes +
            node("0/6", "Generated by DeepSeek AI").copy(visible = false))).profileVerified)
    }
    @Test fun unfamiliarPageDraftAndChangedVersionAreRejected() {
        val o = observation("你好，有什么我能帮你的吗？")
        assertFalse(DeepSeekProbeProfile.empty(task, observation("Unknown page")))
        assertFalse(DeepSeekProbeProfile.empty(task, o.copy(nodes = o.nodes + node("0/4", "unexpected dialog"))))
        assertFalse(DeepSeekProbeProfile.empty(task, o.copy(nodes = o.nodes.map { if (it.path == input.path) it.copy(text = "private draft") else it })))
        assertFalse(DeepSeekProbeProfile.empty(task, o.copy(nodes = o.nodes + node("0/5", "hidden conversation").copy(visible = false))))
        assertFalse(DeepSeekProbeProfile.empty(task, o.copy(appVersion = "different")))
        assertFalse(DeepSeekProbeProfile.empty(task.copy(goal = "arbitrary task"), o))
    }
    @Test fun ambiguousOrNonWritableInputIsNotVerified() {
        val o = observation("你好，有什么我能帮你的吗？")
        assertFalse(DeepSeekProbeProfile.classify(task, o.copy(nodes = o.nodes + input.copy(path = "0/4"))).profileVerified)
        assertFalse(DeepSeekProbeProfile.classify(task, o.copy(nodes = o.nodes.map { it.copy(supportedActions = emptySet()) })).profileVerified)
    }

    @Test fun sendLabelMapsOnlyToItsUniqueClickableAncestorAfterExactStaging() {
        val payload = org.phoneai.teamwork.workflow.PayloadBuilder.build(task, task.steps.first())
        val staged = task.copy(
            steps = listOf(task.steps.first().copy(status = TurnStatus.STAGED, payloadId = payload.id)),
            payloads = mapOf(payload.id to payload))
        val control = node("0/5").copy(clickable = true, supportedActions = setOf(16), bounds = "886 1460 1048 1617")
        val label = node("0/5/0/0", description = "发送").copy(bounds = "949 1523 991 1565")
        val raw = observation("欢迎回来，想从哪里开始？").copy(nodes =
            observation("欢迎回来，想从哪里开始？").nodes.map {
                if (it.path == input.path) it.copy(text = payload.text, bounds = "74 1380 1001 1440") else it
            } + listOf(control, node("0/5/0").copy(bounds = control.bounds), label))
        val classified = DeepSeekProbeProfile.classify(staged, raw)
        assertEquals(NodeRole.SEND, classified.nodes.single { it.path == control.path }.role)
        assertEquals(classified.target(control), DeepSeekProbeProfile.sendTarget(staged, classified, classified.target(label)))
        val rebinding = staged.copy(status = TaskStatus.RUNNING,
            bindings = mapOf("deepseek" to ThreadBinding(staged.id, "deepseek", "", "", participant.version, initialWindowId = 99)))
        assertTrue(DeepSeekProbeProfile.canRebindEmptyWindow(rebinding, classified))
        assertFalse(DeepSeekProbeProfile.canRebindEmptyWindow(rebinding.copy(pendingIntent = "uncertain-send"), classified))
        assertFalse(DeepSeekProbeProfile.canRebindEmptyWindow(rebinding.copy(messages = mapOf("prior" to
            Message("prior", rebinding.id, rebinding.steps.first().id, "deepseek", "prior", Completeness.COMPLETE, "proof"))), classified))
        assertFalse(DeepSeekProbeProfile.canRebindEmptyWindow(rebinding, classified.copy(nodes =
            classified.nodes.map { if (it.role == NodeRole.INPUT) it.copy(text = "other draft") else it })))
        val englishRaw = raw.copy(nodes = raw.nodes.map {
            when {
                it.description == "开启新对话" -> it.copy(description = "New chat")
                it.path == label.path -> it.copy(description = "Send")
                it.text == "欢迎回来，想从哪里开始？" -> it.copy(text = "Hi! What's on your mind today?")
                else -> it
            }
        })
        val englishChecked = DeepSeekProbeProfile.classify(staged, englishRaw)
        assertEquals(NodeRole.SEND, englishChecked.nodes.single { it.path == control.path }.role)
        assertEquals(englishChecked.target(control), DeepSeekProbeProfile.sendTarget(staged, englishChecked,
            englishChecked.target(englishChecked.nodes.single { it.path == label.path })))
        assertNull(DeepSeekProbeProfile.sendTarget(staged, classified, classified.target(control)))
        val duplicate = raw.copy(nodes = raw.nodes + label.copy(path = "0/6/0", description = "发送"))
        assertNull(DeepSeekProbeProfile.sendTarget(staged, DeepSeekProbeProfile.classify(staged, duplicate), duplicate.target(label)))
        for (bad in listOf(
            raw.copy(nodes = raw.nodes.map { if (it.path == label.path) it.copy(visible = false) else it }),
            raw.copy(nodes = raw.nodes.map { if (it.path == label.path) it.copy(enabled = false) else it }),
            raw.copy(nodes = raw.nodes.map { if (it.path == control.path) it.copy(enabled = false) else it }),
            raw.copy(nodes = raw.nodes.map { if (it.path == control.path) it.copy(bounds = "0 1200 1080 1700") else it }),
            raw.copy(nodes = raw.nodes.map { if (it.path == control.path) it.copy(supportedActions = emptySet()) else it })
        )) {
            val checked = DeepSeekProbeProfile.classify(staged, bad)
            assertNull(DeepSeekProbeProfile.sendTarget(staged, checked, checked.target(
                checked.nodes.single { it.path == label.path })))
        }
    }
}
