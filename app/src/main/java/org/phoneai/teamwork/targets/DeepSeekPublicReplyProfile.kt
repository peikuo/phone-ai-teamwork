package org.phoneai.teamwork.targets

import org.phoneai.teamwork.agent.UiNode
import org.phoneai.teamwork.agent.UiObservation
import org.phoneai.teamwork.state.*
import org.phoneai.teamwork.workflow.PayloadBuilder

/** Evidence for one fixed, public DeepSeek 2.5.2 exchange. Not a general answer extractor. */
object DeepSeekPublicReplyProfile {
    data class Verified(val userPath: String, val answerPath: String, val answer: String)
    private const val EMPTY_INPUT_HINT = "Type a message or hold to speak"
    private val generationControls = setOf("Stop", "Stop generating", "Stop generation",
        "Stop response", "Generating", "Thinking...", "停止生成", "正在生成", "生成中")
    private fun allowedText(payloadText: String?) = setOf(payloadText, DeepSeekProbeProfile.ANSWER,
        "Generated by DeepSeek AI", "Think", "Search", EMPTY_INPUT_HINT)
    private data class Box(val left: Int, val top: Int, val right: Int, val bottom: Int)
    private fun box(node: UiNode): Box? {
        val parts = node.bounds.split(' ').mapNotNull(String::toIntOrNull)
        if (parts.size != 4 || parts[0] >= parts[2] || parts[1] >= parts[3]) return null
        return Box(parts[0], parts[1], parts[2], parts[3])
    }
    private fun messageSiblings(userPath: String, answerPath: String): Boolean {
        val user = userPath.split('/')
        val answer = answerPath.split('/')
        val common = user.zip(answer).takeWhile { it.first == it.second }.size
        return common > 3 && user.getOrNull(common) == "1" && answer.getOrNull(common) == "2"
    }
    /** Debug metadata only. Never returns page text or hashes of unknown text. */
    fun diagnostics(task: TaskState, o: UiObservation): String {
        val binding = task.bindings["deepseek"]
        val payload = task.current?.payloadId?.let(task.payloads::get)
        val knownText = allowedText(payload?.text)
        val users = o.nodes.filter { it.text == payload?.text && it.visible && it.enabled && !it.editable }
        val answers = o.nodes.filter { it.text == DeepSeekProbeProfile.ANSWER && it.visible && it.enabled && !it.editable }
        return "profileWindowMatches=${binding?.initialWindowId == o.windowId}" +
            "\nprofileTaskStatus=${task.status}\nprofileTurn=${task.current?.status}" +
            "\nprofilePending=${task.pendingIntent != null}\nprofileNodeCount=${o.nodes.size}" +
            "\nprofileTruncated=${o.truncated}\nprofileLocked=${o.locked}\nprofileObstructed=${o.obstructed}" +
            "\nprofileUserCandidates=${users.size}\nprofileAnswerCandidates=${answers.size}" +
            "\nprofileCopyCount=${o.nodes.count { it.description == "Copy" && it.visible && it.enabled }}" +
            "\nprofileRegenerateCount=${o.nodes.count { it.description == "Regenerate" && it.visible && it.enabled }}" +
            "\nprofileUnknownTextCount=${o.nodes.count { it.text.isNotBlank() && it.text !in knownText }}" +
            "\nprofileUnknownTextMeta=${o.nodes.filter { it.text.isNotBlank() && it.text !in knownText }.joinToString(";") { "${it.path}:${it.text.length}:${it.bounds}:${it.visible}:${it.editable}:${it.className}" }}" +
            "\nprofileGenerationControlCount=${o.nodes.count { it.visible && it.enabled && (it.text in generationControls || it.description in generationControls) }}"
    }
    fun verify(task: TaskState, o: UiObservation, now: Long): Verified? {
        if (task.goal != DeepSeekProbeProfile.GOAL || task.steps.size != 1 ||
            task.status != TaskStatus.RUNNING || task.current?.status != TurnStatus.SUBMITTING ||
            task.pendingIntent.isNullOrBlank() || task.participants.size != 1 ||
            task.participants.single().id != "deepseek" ||
            task.participants.single().packageName != "com.deepseek.chat" ||
            task.participants.single().version != "2.5.2 (273)" ||
            o.taskId != task.id || o.packageName != "com.deepseek.chat" ||
            o.appVersion != "2.5.2 (273)" || o.truncated || o.locked || o.obstructed ||
            now - o.at !in 0..5000) return null
        val binding = task.bindings["deepseek"] ?: return null
        if (binding.taskId != task.id || binding.participantId != "deepseek" ||
            binding.appVersion != o.appVersion || binding.initialWindowId != o.windowId ||
            binding.firstUserText.isNotEmpty() || binding.latestUserText.isNotEmpty()) return null
        val step = task.current ?: return null
        val payload = step.payloadId?.let(task.payloads::get) ?: return null
        if (!PayloadBuilder.matches(task, step, payload)) return null
        val allowedText = allowedText(payload.text)
        if (o.nodes.any { it.visible && it.enabled &&
            (it.text in generationControls || it.description in generationControls) }) return null
        if (o.nodes.any { it.text.isNotBlank() && it.text !in allowedText }) return null
        if (o.nodes.any { it.editable && it.text.isNotBlank() }) return null
        val users = o.nodes.filter { it.text == payload.text && it.visible && it.enabled &&
            !it.editable && it.className == "android.widget.TextView" }
        if (users.size != 1) return null
        val user = users.single()
        val userBox = box(user) ?: return null
        val answers = o.nodes.filter { it.text == DeepSeekProbeProfile.ANSWER && it.visible &&
            it.enabled && !it.editable && it.className == "android.widget.TextView" }
        val verified = answers.mapNotNull { answer ->
            val answerBox = box(answer) ?: return@mapNotNull null
            if (!messageSiblings(user.path, answer.path) || answerBox.top <= userBox.bottom ||
                answerBox.left >= userBox.left || answerBox.right >= userBox.right) return@mapNotNull null
            val parent = answer.path.substringBeforeLast('/', "")
            val copy = o.nodes.filter { it.description == "Copy" && it.path.startsWith("$parent/") &&
                it.visible && it.enabled }
            val regenerate = o.nodes.filter { it.description == "Regenerate" &&
                it.path.startsWith("$parent/") && it.visible && it.enabled }
            if (copy.size != 1 || regenerate.size != 1 ||
                box(copy.single())?.top?.let { it > answerBox.bottom } != true ||
                box(regenerate.single())?.top?.let { it > answerBox.bottom } != true) return@mapNotNull null
            Verified(user.path, answer.path, answer.text)
        }
        return verified.singleOrNull()
    }
}
