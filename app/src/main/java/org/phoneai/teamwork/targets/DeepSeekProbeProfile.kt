package org.phoneai.teamwork.targets

import org.phoneai.teamwork.agent.*
import org.phoneai.teamwork.state.*

/** Narrow, version-specific public probe. This is not a general DeepSeek conversation adapter. */
object DeepSeekProbeProfile {
    const val GOAL = "This is a public UI exchange test. Reply with exactly POC_OK_7319. Do not search or add an explanation."
    const val ANSWER = "POC_OK_7319"
    private val greetings = setOf("你好，有什么我能帮你的吗？", "晚上好，有什么我能帮你的吗？",
        "欢迎回来，想从哪里开始？", "Hi! What's on your mind today?")
    private val newChatLabels = setOf("开启新对话", "New chat")
    private val otherUiText = setOf("深度思考", "智能搜索", "回答由 AI 生成，仅供参考",
        "发消息", "发消息或按住说话", "Think", "Search", "Generated by DeepSeek AI")
    private val sendLabels = setOf("发送", "Send")
    private const val CLICK = 16
    fun diagnostics(task: TaskState, o: UiObservation): String = "accepted=${accepts(task, o)}\ngreetingCount=${o.nodes.count { it.text in greetings }}\nnewChatCount=${o.nodes.count { it.description in newChatLabels }}\nclasses=${o.nodes.map { it.className }.distinct()}\nunknownTextLengths=${o.nodes.filter { it.text.isNotBlank() && it.text !in greetings && it.text !in otherUiText && it.text != task.current?.payloadId?.let(task.payloads::get)?.text }.map { it.text.length }}"
    fun accepts(task: TaskState, o: UiObservation): Boolean = task.goal == GOAL && task.steps.size == 1 &&
        task.participants.size == 1 && task.participants.single().id == "deepseek" &&
        task.participants.single().packageName == "com.deepseek.chat" && o.packageName == "com.deepseek.chat" &&
        o.appVersion == "2.5.2 (273)" && o.taskId == task.id && !o.truncated && !o.locked && !o.obstructed

    fun empty(task: TaskState, o: UiObservation): Boolean {
        if (!accepts(task, o)) return false
        val payload = task.current?.payloadId?.let(task.payloads::get)?.text
        val allowed = greetings + otherUiText + payload.orEmpty()
        return o.nodes.count { it.text in greetings } == 1 && o.nodes.any { it.description in newChatLabels } &&
            o.nodes.any { it.className == "androidx.compose.ui.platform.ComposeView" } &&
            o.nodes.all { it.text.isBlank() || it.text in allowed }
    }

    fun classify(task: TaskState, o: UiObservation): UiObservation {
        if (!empty(task, o)) return o.copy(profileVerified = false)
        val inputs = o.nodes.filter { it.editable && it.enabled && it.visible && 2097152 in it.supportedActions }
        if (inputs.size != 1) return o.copy(profileVerified = false)
        val send = if (task.current?.status in setOf(TurnStatus.STAGED, TurnStatus.SUBMITTING) &&
            inputs.single().text == task.current?.payloadId?.let(task.payloads::get)?.text)
            sendControl(o, inputs.single()) else null
        return o.copy(profileVerified = true, nodes = o.nodes.map {
            it.copy(role = when (it.path) {
                inputs.single().path -> NodeRole.INPUT
                send?.path -> NodeRole.SEND
                else -> NodeRole.UNKNOWN
            })
        })
    }
    private fun isSendLabel(node: UiNode) = node.text in sendLabels || node.description in sendLabels
    private data class Box(val left: Int, val top: Int, val right: Int, val bottom: Int) {
        val width get() = right - left
        val height get() = bottom - top
        fun contains(other: Box) = left <= other.left && top <= other.top &&
            right >= other.right && bottom >= other.bottom
    }
    private fun box(node: UiNode): Box? {
        val parts = node.bounds.split(' ').mapNotNull(String::toIntOrNull)
        if (parts.size != 4) return null
        return Box(parts[0], parts[1], parts[2], parts[3]).takeIf { it.width > 0 && it.height > 0 }
    }
    private fun sendControl(o: UiObservation, input: UiNode): UiNode? {
        val labels = o.nodes.filter(::isSendLabel)
        if (labels.size != 1) return null
        val label = labels.single()
        if (!label.enabled || !label.visible) return null
        val inputBox = box(input) ?: return null
        val labelBox = box(label) ?: return null
        var path = label.path
        // Observed DeepSeek 2.5.2 structure: label -> inert wrapper -> clickable send button.
        // Do not search farther into a generic clickable composer.
        repeat(2) {
            if ('/' !in path) return null
            path = path.substringBeforeLast('/')
            val parent = o.nodes.singleOrNull { it.path == path } ?: return null
            if (parent.clickable) {
                if (!parent.enabled || !parent.visible || CLICK !in parent.supportedActions) return null
                val controlBox = box(parent) ?: return null
                if (!controlBox.contains(labelBox) || controlBox.width > inputBox.width / 3 ||
                    controlBox.height > inputBox.height * 4 ||
                    controlBox.left < inputBox.left + inputBox.width * 3 / 4 ||
                    controlBox.top < inputBox.top - inputBox.height ||
                    controlBox.top > inputBox.bottom + inputBox.height * 2 ||
                    controlBox.bottom > inputBox.bottom + inputBox.height * 4) return null
                return parent
            }
        }
        return null
    }
    /** Map the model's unique send-label selection to its actionable ancestor. */
    fun sendTarget(task: TaskState, o: UiObservation, selected: UiTarget): UiTarget? {
        if (task.current?.status != TurnStatus.STAGED || !o.profileVerified ||
            o.nodes.singleOrNull { it.role == NodeRole.INPUT }?.text != task.current?.payloadId?.let(task.payloads::get)?.text)
            return null
        val label = o.nodes.singleOrNull { it.path == selected.nodePath } ?: return null
        if (selected != o.target(label) || !isSendLabel(label)) return null
        val input = o.nodes.singleOrNull { it.role == NodeRole.INPUT } ?: return null
        val control = sendControl(o, input) ?: return null
        if (control.role != NodeRole.SEND) return null
        return o.target(control)
    }
    fun canRebindEmptyWindow(task: TaskState, o: UiObservation): Boolean {
        val binding = task.bindings["deepseek"] ?: return false
        val payload = task.current?.payloadId?.let(task.payloads::get) ?: return false
        return task.status == TaskStatus.RUNNING && task.current?.status == TurnStatus.STAGED &&
            task.cursor == 0 && task.messages.isEmpty() && task.pendingIntent == null &&
            binding.taskId == task.id && binding.participantId == "deepseek" &&
            binding.appVersion == "2.5.2 (273)" && binding.initialWindowId != null &&
            binding.firstUserText.isEmpty() && binding.latestUserText.isEmpty() &&
            o.profileVerified && empty(task, o) &&
            o.nodes.singleOrNull { it.role == NodeRole.INPUT }?.text == payload.text
    }
    fun evidence(task: TaskState, o: UiObservation): ThreadEvidence? {
        val binding = task.bindings["deepseek"] ?: return null
        return if (binding.initialWindowId == o.windowId && empty(task, o))
            ThreadEvidence(task.id, "deepseek", o.id, false, false, verifiedEmptyThread = true) else null
    }
}
